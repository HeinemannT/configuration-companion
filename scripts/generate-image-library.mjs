const WRAP = /^<svg xmlns="http:\/\/www\.w3\.org\/2000\/svg" viewBox="0 0 256 256" fill="currentColor">([\s\S]*)<\/svg>$/;
const inner = (name, weight) => {
  const file = weight === 'regular' ? `regular/${name}.svg` : `${weight}/${name}-${weight}.svg`;
  const svg = tidy(readFileSync(join(core, 'assets', file), 'utf8').trim(), file);
  const m = WRAP.exec(svg);
  need(m, `${file}: not the expected Phosphor wrapper`);
  return m[1];
};
// Phosphor's own metadata: the tags and categories of each icon are its search words.
const { icons: phosphorMeta } = await import(pathToFileURL(join(core, 'dist/index.mjs')).href);
const metaOf = new Map(phosphorMeta.map((m) => [m.name, m]));
const phosphorWords = (name) => {
  const m = metaOf.get(name);
  need(m, `${name}: not in the Phosphor metadata`);
  return uniq([...m.tags.filter((t) => !t.startsWith('*')), ...m.categories]).filter((w) => !name.split('-').includes(w));
};
const seen = new Set();
const buttons = subset.groups.map((g) => [g.name, g.icons.map((name) => {
  need(!seen.has(name), `${name} is listed twice`);
  seen.add(name);
  return [name, inner(name, 'regular'), inner(name, 'fill'), phosphorWords(name)];
})]);

