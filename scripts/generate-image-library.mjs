const uniq = (list) => [...new Set(list.map((w) => w.toLowerCase().trim()).filter(Boolean))];
/** The keywords of a dot or square from its stem: shape, colour, glyph. */
function symbolWords(stem) {
  const m = /^status_(dot|square)_([a-z]+)(?:_([a-z]+))?$/.exec(stem);
  need(m && COLOUR_WORDS[m[2]] && (!m[3] || GLYPH_WORDS[m[3]]), `${stem}: no keywords`);
  return [...SHAPE_WORDS[m[1]], ...COLOUR_WORDS[m[2]], ...(m[3] ? GLYPH_WORDS[m[3]] : []), ...SYMBOL_WORDS,
    ...(['green', 'amber', 'red'].includes(m[2]) && !m[3] ? ['traffic light', 'ampel', 'rag'] : [])];
}
const statusWords = (group, stem) => {
  if (/^status_/.test(stem)) return uniq(symbolWords(stem));
  need(GROUP_WORDS[group] && ITEM_WORDS[stem], `${stem}: no keywords`);
  return uniq([...ITEM_WORDS[stem], ...GROUP_WORDS[group]]);
};
