/** Long decimals cut to 3 places; checked to be a plain, self-contained SVG. */
function tidy(svg, where) {
  const s = svg.replace(/<\?xml[^?]*\?>\s*/g, '').replace(/<!--[\s\S]*?-->/g, '').replace(/>\s+</g, '><')
    .replace(/-?\d+\.\d{4,}/g, (m) => String(Number(Number(m).toFixed(3))));
  need(/^<svg\b[^>]*\bviewBox="[^"]+"/.test(s), `${where}: no viewBox`);
  need(!/<script|<foreignObject|\bon[a-z]+=|(?:xlink:)?href="(?!#)|url\((?!#)/i.test(s), `${where}: script or external reference`);
  return s;
}

