// @vitest-environment happy-dom
import { expect,it,vi } from 'vitest';
import html from './access.html?raw';
import { mountWorkspace } from './workspace.js';
import { clarityFixture } from './__fixtures__/clarity.js';

it('preserves matrix selection and filters through policy navigation, test scenarios and history',async()=>{
  document.body.innerHTML=html.split('<body>')[1].split('</body>')[0].replace(/<script\b[^>]*>[\s\S]*?<\/script>/g,'');
  window.history.replaceState(null,'');localStorage.clear();
  window.HTMLElement.prototype.scrollIntoView=vi.fn();
  const {snapshot,classes,object}=clarityFixture();snapshot.typeChildren=Object.fromEntries(Object.keys(classes).map(t=>[t,[t]]));
  const policy=snapshot.model.policies[0],role=snapshot.model.roles[0];
  let stored;
  const api=vi.fn(async req=>req.operation==='schema'?classes[req.type]:req.operation==='search'?[object]:{element:'TraceRequest',result:false,children:[],details:{},timedOut:false});
  const workspace=mountWorkspace({snapshot,api,notice:vi.fn(),busy:vi.fn(),persist:async read=>{stored=read();}});
  const click=async s=>{expect(document.querySelector(s),s).not.toBeNull();document.querySelector(s).click();await new Promise(r=>setTimeout(r,0));await workspace.flush();};
  await click('[data-command="matrix"]');
  const filter=document.querySelector('[data-matrix-input="roleQ"]');filter.value='Risk';filter.dispatchEvent(new Event('input',{bubbles:true}));
  await click(`[data-matrix-cell="${role.rid}"][data-type="CeRiskAssessment"]`);
  await click(`[data-matrix-open="${policy.rid}"][data-statement="1"]`);
  expect(stored.state.rid).toBe(policy.rid);expect(stored.state.statement).toBe(1);
  await click('[data-command="matrix"]');
  expect(document.querySelector('[data-matrix-input="roleQ"]').value).toBe('Risk');
  expect(document.querySelector('.am-cell[aria-pressed="true"]').dataset.type).toBe('CeRiskAssessment');
  await click('[data-matrix-test]');
  expect(stored.state.matrixTesting).toBe(true);
  expect(document.querySelector('[data-command="choose-test-role"]').textContent).toContain(role.name);
  await click('[data-command="choose-object"]');
  expect(document.querySelector('[data-command="picker-browse-types"]').textContent).toContain('CeRiskAssessment');
  await click('[data-command="close-picker"]');
  const body=document.querySelector('.test-body');body.scrollTop=300;body.dispatchEvent(new Event('scroll'));
  await click('[data-command="history"]');await click('[data-command="history"]');
  expect(stored.state.matrixTesting).toBe(true);
  expect(document.querySelector('.test-body').scrollTop).toBe(300);
  await click('[data-command="close-test"]');
  expect(stored.state.matrixShowing).toBe(true);
  expect(document.querySelector('.am-cell[aria-pressed="true"]').dataset.type).toBe('CeRiskAssessment');
  await click('[data-matrix-test]');
  expect(document.querySelector('.test-body').scrollTop).toBe(0);
  expect(api.mock.calls.filter(([r])=>r.operation==='trace')).toHaveLength(0);
  await click('[data-command="test-action"][data-action-value="Create"]');
  await click('[data-command="create-view"][data-create-view="json"]');
  const json=document.querySelector('[data-check="proposed"]');
  json.value='{"type":';json.dispatchEvent(new Event('input',{bubbles:true}));
  await click('[data-command="matrix"]');
  await click('[data-command="matrix-test"]');
  expect(document.querySelector('#dock').hidden).toBe(false);
  expect(document.querySelector('[data-check="proposed"]').value).toBe('{"type":');
  await click('[data-command="test-action"][data-action-value="Read"]');
  await click('[data-command="test-action"][data-action-value="Create"]');
  expect(document.querySelector('[data-check="proposed"]').value).toBe('{"type":');
  expect(document.querySelector('[data-command="prepare-check"]').disabled).toBe(true);
});
